#!/usr/bin/env node
// Build the vendored helper and stamp the emitted SDK with its artifact capability.
import { spawnSync } from "node:child_process";
import { chmodSync, copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const packageDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(packageDir, "../..");

export function requestedProcwardIncluded(env = process.env) {
	if (env.PROCWARD !== undefined && env.PROCWARD !== "0" && env.PROCWARD !== "1") {
		throw new Error("PROCWARD must be 0 or 1 (unset defaults to 1)");
	}
	return env.PROCWARD !== "0";
}

function flagSource(included) {
	return `// Generated by build-procward.mjs; do not edit.\nexport const procwardIncluded = ${included};\n`;
}

export function assertProcwardBuild(directory = packageDir, env = process.env) {
	const included = requestedProcwardIncluded(env);
	let emitted;
	try {
		emitted = readFileSync(join(directory, "dist/utils/procward-build.js"), "utf8");
	} catch {
		// This is a build artifact boundary, not runtime capability detection.
	}
	if (emitted !== flagSource(included)) {
		throw new Error(`PROCWARD=${Number(included)} requires a preceding matching package build; rebuild without --skip-build`);
	}
	return included;
}

export function assertProcwardBundleBuild(directory = packageDir, env = process.env) {
	const included = assertProcwardBuild(directory, env);
	let bundled;
	try {
		bundled = readFileSync(join(directory, "dist/bundle/procward-build.js"), "utf8");
	} catch {
		// A missing bundle stamp means the preceding bundle build did not finish.
	}
	if (bundled !== flagSource(included)) throw new Error("procward bundle capability mismatch; rebuild without --skip-build");
	return included;
}

export function buildProcward({ root = repoRoot, directory = packageDir, target, out, offline = false, stageOnly = false, env = process.env } = {}) {
	const included = requestedProcwardIncluded(env);
	const nativeRoot = join(directory, "native/procward");
	const flagPath = join(directory, "dist/utils/procward-build.js");
	if (stageOnly) {
		assertProcwardBundleBuild(directory, env);
		if (!out) throw new Error("--stage-only requires --out");
	} else {
		// Invalidate before work: a failed enabled build must not look complete.
		rmSync(flagPath, { force: true });
		rmSync(join(directory, "dist/bundle/procward-build.js"), { force: true });
		rmSync(nativeRoot, { recursive: true, force: true });
	}
	if (out) rmSync(out, { recursive: true, force: true });
	if (included) {
		const triple = target ?? env.CARGO_BUILD_TARGET;
		const vendor = join(root, "vendor/procward");
		const targetDir = resolve(root, env.CARGO_TARGET_DIR || join(vendor, "target"));
		const args = ["build", "--manifest-path", join(vendor, "Cargo.toml"), "--release", "--locked", "--target-dir", targetDir];
		if (triple) args.push("--target", triple);
		if (offline) args.push("--offline");
		// Cargo owns incremental validation of current sources/target; never reuse staged binaries.
		const result = spawnSync("cargo", args, { cwd: vendor, env, stdio: "inherit" });
		if (result.error || result.status !== 0) {
			throw new Error("procward build failed: Cargo and vendored sources are required; use PROCWARD=0 to omit ownership", { cause: result.error });
		}
		const binaryName = (triple ? triple.includes("windows") : process.platform === "win32") ? "procward.exe" : "procward";
		const binary = join(targetDir, ...(triple ? [triple] : []), "release", binaryName);
		const staged = join(nativeRoot, triple || "host");
		for (const destination of [...(stageOnly ? [] : [staged]), ...(out ? [out] : [])]) {
			mkdirSync(destination, { recursive: true });
			copyFileSync(binary, join(destination, binaryName));
			if (binaryName === "procward") chmodSync(join(destination, binaryName), 0o755);
			copyFileSync(join(vendor, "LICENSE"), join(destination, "LICENSE"));
		}
	}
	if (!stageOnly) {
		mkdirSync(dirname(flagPath), { recursive: true });
		writeFileSync(flagPath, flagSource(included));
	}
	return included;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const { values } = parseArgs({ options: {
		triple: { type: "string" }, out: { type: "string" }, offline: { type: "boolean" }, "stage-only": { type: "boolean" }, check: { type: "boolean" },
	} });
	if (values.check) assertProcwardBundleBuild();
	else buildProcward({ target: values.triple, out: values.out && resolve(values.out), offline: values.offline, stageOnly: values["stage-only"] });
}
