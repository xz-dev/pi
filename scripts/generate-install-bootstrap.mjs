#!/usr/bin/env node

/**
 * Generate thin install.sh / install.ps1 bootstrap assets for a GitHub Release.
 *
 * These scripts are deliberately not installers: they only download and pin-check
 * release-manifest.json + install.ts from an exact Release tag/base URL, choose
 * Node 22.19+ or Bun, then exec install.ts with the original arguments.
 *
 * Transaction logic (install/update/migrate/rollback) lives exclusively in install.ts.
 */

import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { DEFAULT_MINIMUM_NODE_VERSION, REPOSITORY } from "./lib/github-release.mjs";

export const INSTALL_TS_FILENAME = "install.ts";
export const INSTALL_SH_FILENAME = "install.sh";
export const INSTALL_PS1_FILENAME = "install.ps1";
export const RELEASE_MANIFEST_FILENAME = "release-manifest.json";
export const ATTESTATION_BUNDLE_FILENAME = "attestation-subjects.txt";

/**
 * Canonical per-tag download base URL for a published GitHub Release.
 * Trailing slash is required so URL joins resolve as sibling assets.
 */
export function releaseDownloadBaseUrl(tag, repository = REPOSITORY) {
	if (typeof tag !== "string" || !tag.trim()) {
		throw new Error("releaseDownloadBaseUrl requires a non-empty tag");
	}
	return `https://github.com/${repository}/releases/download/${tag}/`;
}

function assertBootstrapPins(options) {
	const {
		tag,
		baseUrl,
		manifestSha256,
		installTsSha256,
		installTsBytes,
		minimumNodeVersion = DEFAULT_MINIMUM_NODE_VERSION,
	} = options ?? {};
	if (typeof tag !== "string" || !/^xz-v\d+\.\d+\.\d+-xz\.\d+\.\d+\.g[0-9a-f]{8}$/.test(tag)) {
		throw new Error("bootstrap requires an exact xz Release tag");
	}
	let releaseUrl;
	try {
		releaseUrl = new URL(baseUrl);
	} catch {
		throw new Error("bootstrap requires an absolute baseUrl");
	}
	const isLocalTestUrl =
		releaseUrl.protocol === "http:" &&
		["127.0.0.1", "localhost", "[::1]"].includes(releaseUrl.hostname);
	const isProductionUrl =
		releaseUrl.protocol === "https:" &&
		releaseUrl.origin === "https://github.com" &&
		releaseUrl.pathname === `/${REPOSITORY}/releases/download/${tag}/`;
	if (
		(!isProductionUrl && !isLocalTestUrl) ||
		releaseUrl.username || releaseUrl.password || releaseUrl.search || releaseUrl.hash ||
		!releaseUrl.pathname.endsWith("/")
	) {
		throw new Error("bootstrap baseUrl must be the exact xz-dev/pi Release tag URL");
	}
	if (typeof manifestSha256 !== "string" || !/^[0-9a-f]{64}$/.test(manifestSha256)) {
		throw new Error("bootstrap requires 64-hex manifestSha256");
	}
	if (typeof installTsSha256 !== "string" || !/^[0-9a-f]{64}$/.test(installTsSha256)) {
		throw new Error("bootstrap requires 64-hex installTsSha256");
	}
	if (!Number.isInteger(installTsBytes) || installTsBytes <= 0) {
		throw new Error("bootstrap requires positive integer installTsBytes");
	}
	if (typeof minimumNodeVersion !== "string" || !/^\d+\.\d+\.\d+$/.test(minimumNodeVersion)) {
		throw new Error("bootstrap requires minimumNodeVersion like 22.19.0");
	}
	return {
		tag,
		baseUrl,
		manifestSha256,
		installTsSha256,
		installTsBytes,
		minimumNodeVersion,
	};
}

function shellSingleQuote(value) {
	return `'${String(value).replaceAll("'", `'\"'\"'`)}'`;
}

/**
 * POSIX sh bootstrap. Uses curl only for pinned Release asset downloads.
 */
export function generateInstallSh(options) {
	const pins = assertBootstrapPins(options);
	const tagQ = shellSingleQuote(pins.tag);
	const baseUrlQ = shellSingleQuote(pins.baseUrl);
	const manifestShaQ = shellSingleQuote(pins.manifestSha256);
	const installShaQ = shellSingleQuote(pins.installTsSha256);
	const installBytes = String(pins.installTsBytes);
	const minNodeQ = shellSingleQuote(pins.minimumNodeVersion);
	const manifestNameQ = shellSingleQuote(RELEASE_MANIFEST_FILENAME);
	const installNameQ = shellSingleQuote(INSTALL_TS_FILENAME);
	const bundleNameQ = shellSingleQuote(ATTESTATION_BUNDLE_FILENAME);

	return `#!/bin/sh
# Thin Pi GitHub Release bootstrap. Not the installer.
# Pinned to exact tag/base URL + release-manifest.json / install.ts digests.
# Generated by scripts/generate-install-bootstrap.mjs — do not hand-edit.
set -eu

TAG=${tagQ}
BASE_URL=${baseUrlQ}
MANIFEST_SHA256=${manifestShaQ}
INSTALL_TS_SHA256=${installShaQ}
INSTALL_TS_BYTES=${installBytes}
MINIMUM_NODE_VERSION=${minNodeQ}
MANIFEST_NAME=${manifestNameQ}
INSTALL_TS_NAME=${installNameQ}
BUNDLE_NAME=${bundleNameQ}

if ! command -v curl >/dev/null 2>&1; then
	echo "pi bootstrap: curl is required" >&2
	exit 1
fi
if ! command -v gh >/dev/null 2>&1; then
	echo "pi bootstrap: GitHub CLI (gh) is required for artifact attestation verification" >&2
	exit 1
fi
if ! command -v openssl >/dev/null 2>&1; then
	echo "pi bootstrap: openssl is required for SHA-256 verification" >&2
	exit 1
fi

WORKDIR=\${TMPDIR:-/tmp}
WORKDIR=\$(mktemp -d "\$WORKDIR/pi-xz-bootstrap.XXXXXX")
cleanup() {
	rm -rf "\$WORKDIR"
}
trap cleanup EXIT INT TERM

MANIFEST_PATH="\$WORKDIR/\$MANIFEST_NAME"
INSTALL_TS_PATH="\$WORKDIR/\$INSTALL_TS_NAME"
BUNDLE_PATH="\$WORKDIR/\$BUNDLE_NAME"

curl -fsSL "\$BASE_URL\$MANIFEST_NAME" -o "\$MANIFEST_PATH"
curl -fsSL "\$BASE_URL\$INSTALL_TS_NAME" -o "\$INSTALL_TS_PATH"
curl -fsSL "\$BASE_URL\$BUNDLE_NAME" -o "\$BUNDLE_PATH"

hex_sha256() {
	# Portable SHA-256: "hash  -" or "hash *-" depending on openssl build.
	openssl dgst -sha256 "\$1" | awk '{print \$NF}'
}

file_bytes() {
	# Prefer POSIX-friendly size probes; fall back to wc -c.
	if command -v stat >/dev/null 2>&1; then
		size=\$(stat -c %s "\$1" 2>/dev/null || stat -f %z "\$1" 2>/dev/null || true)
		if [ -n "\${size:-}" ]; then
			printf '%s\\n' "\$size"
			return 0
		fi
	fi
	wc -c < "\$1" | tr -d '[:space:]'
}

actual_manifest_sha=\$(hex_sha256 "\$MANIFEST_PATH")
if [ "\$actual_manifest_sha" != "\$MANIFEST_SHA256" ]; then
	echo "pi bootstrap: release-manifest.json sha256 mismatch" >&2
	echo "  expected: \$MANIFEST_SHA256" >&2
	echo "  actual:   \$actual_manifest_sha" >&2
	exit 1
fi

actual_install_sha=\$(hex_sha256 "\$INSTALL_TS_PATH")
if [ "\$actual_install_sha" != "\$INSTALL_TS_SHA256" ]; then
	echo "pi bootstrap: install.ts sha256 mismatch" >&2
	echo "  expected: \$INSTALL_TS_SHA256" >&2
	echo "  actual:   \$actual_install_sha" >&2
	exit 1
fi

actual_install_bytes=\$(file_bytes "\$INSTALL_TS_PATH")
if [ "\$actual_install_bytes" != "\$INSTALL_TS_BYTES" ]; then
	echo "pi bootstrap: install.ts size mismatch" >&2
	echo "  expected: \$INSTALL_TS_BYTES bytes" >&2
	echo "  actual:   \$actual_install_bytes bytes" >&2
	exit 1
fi

manifest_commit=\$(sed -n 's/.*"commit"[[:space:]]*:[[:space:]]*"\\([0-9a-f]*\\)".*/\\1/p' "\$MANIFEST_PATH" | head -n 1)
case "\$manifest_commit" in
	""|*[!0-9a-f]*) echo "pi bootstrap: verified manifest has an invalid commit" >&2; exit 1 ;;
esac
if [ "\${#manifest_commit}" -ne 40 ]; then
	echo "pi bootstrap: verified manifest has an invalid commit" >&2
	exit 1
fi
if ! gh attestation verify "\$INSTALL_TS_PATH" \
	--bundle "\$BUNDLE_PATH" \
	--repo xz-dev/pi \
	--signer-workflow xz-dev/pi/.github/workflows/publish-github-release.yml \
	--source-ref refs/heads/main \
	--source-digest "\$manifest_commit" \
	--deny-self-hosted-runners >/dev/null; then
	echo "pi bootstrap: install.ts provenance verification failed" >&2
	exit 1
fi

# Best-effort identity check against the verified manifest (tag + installer pin).
# Keep this as awk/sed only — bootstrap must not become an installer.
manifest_tag=\$(sed -n 's/.*"tag"[[:space:]]*:[[:space:]]*"\\([^"]*\\)".*/\\1/p' "\$MANIFEST_PATH" | head -n 1)
if [ -z "\$manifest_tag" ]; then
	echo "pi bootstrap: verified manifest is missing tag" >&2
	exit 1
fi
if [ "\$manifest_tag" != "\$TAG" ]; then
	echo "pi bootstrap: manifest tag \$manifest_tag does not match pinned tag \$TAG" >&2
	exit 1
fi

version_ge() {
	# Return 0 when \$1 >= \$2 for dotted numeric versions (no pre-release).
	a=\$1
	b=\$2
	old_ifs=\$IFS
	IFS=.
	set -- \$a
	a1=\${1:-0}; a2=\${2:-0}; a3=\${3:-0}
	set -- \$b
	b1=\${1:-0}; b2=\${2:-0}; b3=\${3:-0}
	IFS=\$old_ifs
	if [ "\$a1" -gt "\$b1" ]; then return 0; fi
	if [ "\$a1" -lt "\$b1" ]; then return 1; fi
	if [ "\$a2" -gt "\$b2" ]; then return 0; fi
	if [ "\$a2" -lt "\$b2" ]; then return 1; fi
	if [ "\$a3" -ge "\$b3" ]; then return 0; fi
	return 1
}

RUNTIME=""
if command -v node >/dev/null 2>&1; then
	node_version=\$(node -p "process.versions.node" 2>/dev/null || true)
	if [ -n "\$node_version" ] && version_ge "\$node_version" "\$MINIMUM_NODE_VERSION"; then
		RUNTIME=\$(command -v node)
	fi
fi
if [ -z "\$RUNTIME" ]; then
	if command -v bun >/dev/null 2>&1; then
		RUNTIME=\$(command -v bun)
	else
		echo "pi bootstrap: need Node.js >= \$MINIMUM_NODE_VERSION or Bun on PATH" >&2
		exit 1
	fi
fi

# Point install.ts at this exact Release; pass through all CLI args (--migrate, etc.).
export PI_XZ_RELEASE_BASE_URL="\$BASE_URL"
export PI_XZ_RELEASE_EXACT_BASE_URL="\$BASE_URL"
export PI_XZ_RELEASE_MANIFEST_SHA256="\$MANIFEST_SHA256"
exec "\$RUNTIME" "\$INSTALL_TS_PATH" "\$@"
`;
}

/**
 * Windows PowerShell bootstrap. Uses Invoke-WebRequest only for pinned Release asset downloads.
 */
export function generateInstallPs1(options) {
	const pins = assertBootstrapPins(options);
	// PowerShell single-quoted strings only need '' escapes.
	const q = (value) => `'${String(value).replaceAll("'", "''")}'`;

	return `# Thin Pi GitHub Release bootstrap. Not the installer.
# Pinned to exact tag/base URL + release-manifest.json / install.ts digests.
# Generated by scripts/generate-install-bootstrap.mjs — do not hand-edit.
$ErrorActionPreference = 'Stop'

$Tag = ${q(pins.tag)}
$BaseUrl = ${q(pins.baseUrl)}
$ManifestSha256 = ${q(pins.manifestSha256)}
$InstallTsSha256 = ${q(pins.installTsSha256)}
$InstallTsBytes = ${pins.installTsBytes}
$MinimumNodeVersion = [version]${q(pins.minimumNodeVersion)}
$ManifestName = ${q(RELEASE_MANIFEST_FILENAME)}
$InstallTsName = ${q(INSTALL_TS_FILENAME)}
$BundleName = ${q(ATTESTATION_BUNDLE_FILENAME)}

$ghCmd = Get-Command gh -ErrorAction SilentlyContinue
if ($null -eq $ghCmd) {
	throw "pi bootstrap: GitHub CLI (gh) is required for artifact attestation verification"
}

$workDir = Join-Path ([System.IO.Path]::GetTempPath()) ("pi-xz-bootstrap-" + [guid]::NewGuid().ToString("N"))
New-Item -ItemType Directory -Path $workDir | Out-Null
try {
	$manifestPath = Join-Path $workDir $ManifestName
	$installTsPath = Join-Path $workDir $InstallTsName
	$bundlePath = Join-Path $workDir $BundleName

	Invoke-WebRequest -Uri ($BaseUrl + $ManifestName) -OutFile $manifestPath -UseBasicParsing
	Invoke-WebRequest -Uri ($BaseUrl + $InstallTsName) -OutFile $installTsPath -UseBasicParsing
	Invoke-WebRequest -Uri ($BaseUrl + $BundleName) -OutFile $bundlePath -UseBasicParsing

	function Get-Sha256Hex([string] $Path) {
		$hash = Get-FileHash -Algorithm SHA256 -Path $Path
		return $hash.Hash.ToLowerInvariant()
	}

	$actualManifestSha = Get-Sha256Hex $manifestPath
	if ($actualManifestSha -ne $ManifestSha256) {
		throw "pi bootstrap: release-manifest.json sha256 mismatch (expected $ManifestSha256, actual $actualManifestSha)"
	}

	$actualInstallSha = Get-Sha256Hex $installTsPath
	if ($actualInstallSha -ne $InstallTsSha256) {
		throw "pi bootstrap: install.ts sha256 mismatch (expected $InstallTsSha256, actual $actualInstallSha)"
	}

	$actualInstallBytes = (Get-Item -LiteralPath $installTsPath).Length
	if ($actualInstallBytes -ne $InstallTsBytes) {
		throw "pi bootstrap: install.ts size mismatch (expected $InstallTsBytes bytes, actual $actualInstallBytes bytes)"
	}

	$manifestJson = Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json
	if ($null -eq $manifestJson.tag) {
		throw "pi bootstrap: verified manifest is missing tag"
	}
	if ($manifestJson.tag -ne $Tag) {
		throw "pi bootstrap: manifest tag $($manifestJson.tag) does not match pinned tag $Tag"
	}
	if ($manifestJson.commit -notmatch '^[0-9a-f]{40}$') {
		throw "pi bootstrap: verified manifest has an invalid commit"
	}

	& $ghCmd.Source attestation verify $installTsPath ${"`"}
		--bundle $bundlePath ${"`"}
		--repo xz-dev/pi ${"`"}
		--signer-workflow xz-dev/pi/.github/workflows/publish-github-release.yml ${"`"}
		--source-ref refs/heads/main ${"`"}
		--source-digest $manifestJson.commit ${"`"}
		--deny-self-hosted-runners | Out-Null
	if ($LASTEXITCODE -ne 0) {
		throw "pi bootstrap: install.ts provenance verification failed"
	}

	$runtime = $null
	$nodeCmd = Get-Command node -ErrorAction SilentlyContinue
	if ($null -ne $nodeCmd) {
		try {
			$nodeVersionText = & $nodeCmd.Source -p "process.versions.node"
			if ($nodeVersionText -and ([version]$nodeVersionText -ge $MinimumNodeVersion)) {
				$runtime = $nodeCmd.Source
			}
		} catch {
			# Fall through to Bun.
		}
	}
	if ($null -eq $runtime) {
		$bunCmd = Get-Command bun -ErrorAction SilentlyContinue
		if ($null -ne $bunCmd) {
			$runtime = $bunCmd.Source
		} else {
			throw "pi bootstrap: need Node.js >= $MinimumNodeVersion or Bun on PATH"
		}
	}

	$env:PI_XZ_RELEASE_BASE_URL = $BaseUrl
	$env:PI_XZ_RELEASE_EXACT_BASE_URL = $BaseUrl
	$env:PI_XZ_RELEASE_MANIFEST_SHA256 = $ManifestSha256
	# Pass through all caller args (--migrate / --rollback / etc.).
	& $runtime $installTsPath @args
	exit $LASTEXITCODE
}
finally {
	Remove-Item -LiteralPath $workDir -Recurse -Force -ErrorAction SilentlyContinue
}
`;
}

/**
 * Write install.sh + install.ps1 into outDir and return their asset metadata.
 */
export function writeInstallBootstrap(outDir, options) {
	const pins = assertBootstrapPins(options);
	const shContent = generateInstallSh(pins);
	const ps1Content = generateInstallPs1(pins);
	const shPath = join(outDir, INSTALL_SH_FILENAME);
	const ps1Path = join(outDir, INSTALL_PS1_FILENAME);
	writeFileSync(shPath, shContent, { encoding: "utf8", mode: 0o755 });
	writeFileSync(ps1Path, ps1Content, { encoding: "utf8" });
	return {
		tag: pins.tag,
		baseUrl: pins.baseUrl,
		minimumNodeVersion: pins.minimumNodeVersion,
		manifestSha256: pins.manifestSha256,
		installTsSha256: pins.installTsSha256,
		installTsBytes: pins.installTsBytes,
		sh: {
			file: INSTALL_SH_FILENAME,
			path: shPath,
			content: shContent,
		},
		ps1: {
			file: INSTALL_PS1_FILENAME,
			path: ps1Path,
			content: ps1Content,
		},
	};
}

function parseCliArgs(argv) {
	const args = argv.slice(2);
	const options = {};
	for (let i = 0; i < args.length; i += 1) {
		const key = args[i];
		const value = args[i + 1];
		if (!value || value.startsWith("--")) {
			throw new Error(`Missing value for ${key}`);
		}
		switch (key) {
			case "--out":
				options.outDir = value;
				break;
			case "--tag":
				options.tag = value;
				break;
			case "--base-url":
				options.baseUrl = value;
				break;
			case "--manifest-sha256":
				options.manifestSha256 = value;
				break;
			case "--install-ts-sha256":
				options.installTsSha256 = value;
				break;
			case "--install-ts-bytes":
				options.installTsBytes = Number(value);
				break;
			case "--minimum-node-version":
				options.minimumNodeVersion = value;
				break;
			default:
				throw new Error(`Unknown argument: ${key}`);
		}
		i += 1;
	}
	if (!options.outDir) {
		throw new Error(
			"Usage: node scripts/generate-install-bootstrap.mjs --out <dir> --tag <tag> --base-url <url/> --manifest-sha256 <hex> --install-ts-sha256 <hex> --install-ts-bytes <n> [--minimum-node-version 22.19.0]",
		);
	}
	return options;
}

function main() {
	const { outDir, ...pins } = parseCliArgs(process.argv);
	const written = writeInstallBootstrap(outDir, pins);
	console.log(written.sh.path);
	console.log(written.ps1.path);
}

const isMain =
	Boolean(process.argv[1]) && fileURLToPath(import.meta.url) === resolve(process.argv[1]);
if (isMain) {
	main();
}
