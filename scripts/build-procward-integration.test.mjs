import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { chmodSync, copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";
import { processOwnerEnabled } from "./lib/bun-targets.mjs";

const source = dirname(fileURLToPath(import.meta.url));
function put(path, contents) { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, contents); }
function flag(included) { return `// Generated by build-procward.mjs; do not edit.\nexport const procwardIncluded = ${included};\n`; }
function fixture(t, included) {
	const root = mkdtempSync(join(tmpdir(), "pi-ci-procward-"));
	t.after(() => rmSync(root, { recursive: true, force: true }));
	mkdirSync(join(root, "scripts/lib"), { recursive: true });
	copyFileSync(join(source, "build-binaries.sh"), join(root, "scripts/build-binaries.sh"));
	copyFileSync(join(source, "lib/bun-targets.mjs"), join(root, "scripts/lib/bun-targets.mjs"));
	put(join(root, "packages/coding-agent/package.json"), '{"name":"fixture","version":"1.0.0"}');
	put(join(root, "packages/coding-agent/dist/utils/procward-build.js"), flag(included));
	const log = join(root, "calls");
	put(join(root, "packages/coding-agent/scripts/build-procward.mjs"), `
import fs from "node:fs";
const args = process.argv.slice(2);
fs.appendFileSync(process.env.CALL_LOG, JSON.stringify({command:"builder", args})+"\\n");
if (args.includes("--check")) {
 const flag = fs.readFileSync("packages/coding-agent/dist/utils/procward-build.js","utf8");
 if (!flag.includes(" = "+(process.env.PROCWARD !== "0")+";")) throw Error("preceding matching package build required");
} else {
 if (!args.includes("--stage-only")) throw Error("must not mutate npm output");
 if (process.env.FAIL_HELPER) process.exit(19);
 const out = args[args.indexOf("--out")+1]; fs.mkdirSync(out,{recursive:true});
 fs.writeFileSync(out+"/procward","DO NOT EXECUTE"); fs.chmodSync(out+"/procward",0o755); fs.writeFileSync(out+"/LICENSE","BSD sentinel");
}
`);
	const bin = join(root, "bin");
	put(join(bin, "bun"), `#!${process.execPath}
const fs = require("node:fs");
const args = process.argv.slice(2);
const asset = args.find(x=>x.startsWith("--asset=") && x.endsWith("/process-owner"));
const owner = asset && asset.slice(8);
const inventory = {args, helper:owner && fs.readFileSync(owner+"/procward","utf8"), mode:owner && (fs.statSync(owner+"/procward").mode&511), license:owner && fs.readFileSync(owner+"/LICENSE","utf8")};
fs.appendFileSync(process.env.CALL_LOG,JSON.stringify({command:"bun",...inventory})+"\\n");
fs.writeFileSync(args[args.indexOf("--outfile")+1],JSON.stringify(inventory));
`);
	put(join(bin, "readelf"), `#!${process.execPath}
require("node:fs").appendFileSync(process.env.CALL_LOG,JSON.stringify({command:"readelf",args:process.argv.slice(2)})+"\\n");
if(process.env.FAIL_READELF) process.exit(9);
console.log("(NEEDED) [libc.so.7]\\n(NEEDED) [libthr.so.3]"+(process.env.BAD_NEEDED ? "\\n(NEEDED) [libutil.so.10]" : ""));
`);
	for (const command of ["cargo", "rustc", "rustup", "procward"]) put(join(bin, command), `#!${process.execPath}\nrequire("node:fs").appendFileSync(process.env.CALL_LOG,"UNEXPECTED EXECUTION\\n");process.exit(99);\n`);
	for (const command of ["bun", "readelf", "cargo", "rustc", "rustup", "procward"]) chmodSync(join(bin, command), 0o755);
	symlinkSync(process.execPath, join(bin, "node"));
	return { root, log, env: { ...process.env, PATH: `${bin}:/usr/bin:/bin`, CALL_LOG: log, PROCWARD: included ? "1" : "0" } };
}
function run(f, platform = "linux-x64-gnu-baseline", env = f.env) {
	return spawnSync("bash", ["scripts/build-binaries.sh", "--skip-install", "--skip-build", "--without-x11", "--platform", platform, "--out", join(f.root, "out")], { cwd: f.root, env, encoding: "utf8" });
}
function calls(f) { return existsSync(f.log) ? readFileSync(f.log, "utf8").trim().split("\n").map(x => JSON.parse(x)) : []; }

test("feature detection reads the emitted capability, not obsolete builder presence or runtime PROCWARD", t => {
	const f = fixture(t, false);
	assert.equal(processOwnerEnabled(f.root), false);
	put(join(f.root, "packages/coding-agent/dist/utils/procward-build.js"), flag(true));
	assert.equal(processOwnerEnabled(f.root), true);
	rmSync(join(f.root, "packages/coding-agent/dist/utils/procward-build.js"));
	assert.equal(processOwnerEnabled(f.root), true); // Before build, never weaken the ownership gate.
	put(join(f.root, "packages/coding-agent/dist/utils/procward-build.js"), "corrupt");
	assert.throws(() => processOwnerEnabled(f.root), /Invalid procward artifact capability/);
	rmSync(join(f.root, "packages/coding-agent/scripts/build-procward.mjs"));
	put(join(f.root, "packages/coding-agent/scripts/build-process-owner.mjs"), "obsolete");
	assert.equal(processOwnerEnabled(f.root), false);
});

test("real CI packer requests canonical Cargo target and embeds process-owner plus literal true", { skip: process.platform === "win32" }, t => {
	const f = fixture(t, true);
	const result = run(f);
	assert.equal(result.status, 0, result.stderr);
	const events = calls(f);
	assert.deepEqual(events[0], {command:"builder",args:["--check"]});
	assert.deepEqual(events[1].args.slice(0,3), ["--stage-only", "--triple", "x86_64-unknown-linux-gnu"]);
	const bun = events.at(-1);
	assert.equal(bun.command, "bun");
	assert.ok(bun.args.includes("--define=PI_PROCWARD_INCLUDED=true"));
	assert.equal(bun.helper, "DO NOT EXECUTE");
	assert.equal(bun.license, "BSD sentinel");
	assert.equal(bun.mode, 0o755);
	assert.ok(bun.args.includes("./src/bun/cli-portable.ts"));
});

test("real CI off packaging has no owner asset, Cargo, helper or staging invocation", { skip: process.platform === "win32" }, t => {
	const f = fixture(t, false);
	const result = run(f);
	assert.equal(result.status, 0, result.stderr);
	const events = calls(f);
	assert.equal(events.length, 2);
	assert.equal(events[1].command, "bun");
	assert.ok(events[1].args.includes("--define=PI_PROCWARD_INCLUDED=false"));
	assert.equal(events[1].args.some(x=>x.endsWith("/process-owner")), false);
});

test("CI packer embeds package-owned skills when present, independently of procward inclusion", { skip: process.platform === "win32" }, t => {
	const f = fixture(t, false);
	assert.equal(run(f).status, 0);
	assert.equal(calls(f).at(-1).args.includes("--asset=.pi/skills"), false);
	put(join(f.root, "packages/coding-agent/.pi/skills/persistent-background-tasks/SKILL.md"), "skill sentinel");
	rmSync(f.log);
	assert.equal(run(f).status, 0);
	const bun = calls(f).at(-1);
	assert.ok(bun.args.includes("--asset=.pi/skills"));
	assert.ok(bun.args.includes("--define=PI_PROCWARD_INCLUDED=false"));
	assert.equal(bun.args.some(x => x.endsWith("/process-owner")), false);
});

test("skip-build mode mismatch and enabled helper build failure stop before Bun", { skip: process.platform === "win32" }, t => {
	const f = fixture(t, true);
	assert.notEqual(run(f, undefined, { ...f.env, PROCWARD: "0" }).status, 0);
	assert.equal(calls(f).some(x=>x.command === "bun"), false);
	rmSync(f.log);
	assert.notEqual(run(f, undefined, { ...f.env, FAIL_HELPER: "1" }).status, 0);
	assert.equal(calls(f).some(x=>x.command === "bun"), false);
});

test("FreeBSD checks procward ELF dependencies and retains readelf/portability failures", { skip: process.platform === "win32" }, t => {
	const f = fixture(t, true);
	assert.equal(run(f, "freebsd-x64").status, 0);
	assert.match(calls(f).find(x=>x.command === "readelf").args[1], /\/process-owner\/procward$/);
	for (const env of [{ FAIL_READELF:"1" }, { BAD_NEEDED:"1" }]) {
		rmSync(f.log);
		assert.notEqual(run(f, "freebsd-x64", { ...f.env, ...env }).status, 0);
		assert.equal(calls(f).some(x=>x.command === "bun"), false);
	}
});
